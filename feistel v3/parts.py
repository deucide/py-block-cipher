#helper functions
def _mult(a, b):
    #multiplication on gf(2**8)/<x8+x7+x5+x+1>
    b=str(bin(b))[2:]
    o, p=[], 0
    for i in range(len(b)):
        if int(b[::-1][i]):
            o.append(a<<i)
    for i in o:
        p^=i
    for i in range(len(str(bin(p)))-11, -1, -1):
        if p>=p^(419<<i):
            p^=419<<i
    return p
def _dot_prod(vec1, vec2):
    #dot prod on galois field
    p, o=[], 0
    for i in range(len(vec1)):
        p.append(_mult(vec1[i], vec2[i]))
    for i in p:
        o^=i #xor is adding on gf
    return o

